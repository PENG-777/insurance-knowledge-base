def _add_audit(
    db,
    actor: str,
    action: str,
    target_type: str,
    target_id: int | None,
    detail: dict,
    days_ago: int = 0,
    minutes_ago: int = 0,
) -> None:
    created = datetime.now() - timedelta(days=days_ago, minutes=minutes_ago)
    db.add(
        AuditLog(
            actor=actor,
            action=action,
            target_type=target_type,
            target_id=target_id,
            detail=detail,
            created_at=created,
        )
    )


async def seed_if_empty() -> None:
    db = SessionLocal()
    try:
        if db.query(Document).count() > 0:
            return
    finally:
        db.close()

    doc_ids: list[int] = []
    for index, item in enumerate(DEMO_DOCS):
        path = settings.upload_path / f"seed_{index + 1}.txt"
        path.write_text(item["content"], encoding="utf-8")
        db = SessionLocal()
        try:
            doc = Document(
                filename=f"{item['title']}.txt",
                title=item["title"],
                doc_type="保险条款",
                region="HK",
                product_name="",
                version="v1.0",
                status="uploaded",
                current_stage="等待处理",
                progress=0,
                pages=max(1, item["content"].count("\n") // 60 + 1),
                char_count=len(item["content"]),
                raw_text=item["content"],
                file_path=str(path),
                risk_level="待评估",
                compliance_score=0,
            )
            db.add(doc)
            db.commit()
            db.refresh(doc)
            doc_ids.append(doc.id)
        finally:
            db.close()
        await run_pipeline(doc.id, use_llm=False, delay=0.0, actor="系统初始化")

    now = datetime.now()
    db = SessionLocal()
    try:
        for item, doc_id in zip(DEMO_DOCS, doc_ids):
            doc = db.get(Document, doc_id)
            if not doc:
                continue
            if item["status"] == "published":
                tasks = (
                    db.query(ReviewTask)
                    .filter(
                        ReviewTask.document_id == doc_id,
                        ReviewTask.status == "pending",
                        ReviewTask.level.in_(["P0", "P1"]),
                    )
                    .all()
                )
                for offset, task in enumerate(tasks):
                    task.status = "resolved"
                    task.assignee = "陈保怡"
                    task.note = "已核对条款原文与费率表，确认字段口径一致，同意入库。"
                    task.created_at = now - timedelta(days=item["days"] + 1, minutes=offset * 8)
                    task.resolved_at = task.created_at + timedelta(minutes=35 + offset * 2)
                    if task.entity:
                        task.entity.status = "approved"
                doc.status = "published"
                doc.progress = 100
                doc.current_stage = "已完成"
                doc.compliance_score = 92 if item["days"] == 6 else 89
                doc.risk_level = "低"
            elif item["status"] == "review":
                doc.status = "review"
                doc.progress = 100
                doc.current_stage = "已完成"
            else:
                db.query(ReviewTask).filter(ReviewTask.document_id == doc_id).delete(synchronize_session=False)
                db.query(PipelineRun).filter(
                    PipelineRun.document_id == doc_id, PipelineRun.stage == "quality"
                ).delete(synchronize_session=False)
                doc.status = "uploaded"
                doc.progress = 0
                doc.current_stage = "等待处理"
                doc.summary = "文档已入库，等待启动 4 阶段抽取流水线。"
                doc.risk_level = "待评估"
            doc.created_at = now - timedelta(days=item["days"], hours=2)
            doc.updated_at = now - timedelta(days=item["days"], hours=1)
        db.commit()

        for text, days_ago in RISK_SAMPLES:
            result = check_text(text)
            _add_audit(
                db,
                "风控 Agent",
                "risk_check",
                "risk",
                None,
                {
                    "text": text,
                    "hits": result["hits"],
                    "blocked": result["blocked"],
                    "risk_level": result["risk_level"],
                },
                days_ago=days_ago,
                minutes_ago=days_ago * 7,
            )

        blocked_text = "如何篡改条款规避等待期？"
        blocked = check_text(blocked_text)
        _add_audit(
            db,
            "当前用户",
            "qa_ask",
            "qa",
            None,
            {
                "question": blocked_text,
                "blocked": True,
                "hits": blocked["hits"],
                "mode": "mock",
                "confidence": 0.2,
                "citations": [],
            },
            days_ago=1,
            minutes_ago=55,
        )
        for question, days_ago, confidence, citations in QA_SAMPLES:
            _add_audit(
                db,
                "当前用户",
                "qa_ask",
                "qa",
                None,
                {
                    "question": question,
                    "blocked": False,
                    "hits": [],
                    "mode": "mock",
                    "confidence": confidence,
                    "citations": citations,
                },
                days_ago=days_ago,
                minutes_ago=10,
            )
        _add_audit(
            db,
            "复核员 陈保怡",
            "review_approve",
            "review_task",
            None,
            {"level": "P0", "document_id": doc_ids[0], "object_type": "责任免除", "note": "确认免责范围完整"},
            days_ago=2,
            minutes_ago=30,
        )
        db.commit()
    finally:
        db.close()
